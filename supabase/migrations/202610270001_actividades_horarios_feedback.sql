begin;

create table if not exists public.app_configuracion (
    id smallint primary key check (id = 1),
    configuracion jsonb not null default '{}'::jsonb,
    actualizado_por text not null default '',
    actualizado_en timestamptz not null default now()
);

insert into public.app_configuracion (id, configuracion)
values (
    1,
    '{
        "dia_asistencia": 0,
        "hora_inicio_asistencia": "14:45",
        "hora_fin_asistencia": "17:00",
        "dias_solicitud_sustituto": [1, 2],
        "motivo": "Horario habitual",
        "actualizado_por": "",
        "actualizado_en": ""
    }'::jsonb
)
on conflict (id) do nothing;

create table if not exists public.eventos_calendario (
    id bigint generated by default as identity primary key,
    titulo text not null,
    descripcion text not null default '',
    fecha date not null,
    tipo text not null default 'evento' check (tipo in ('evento', 'actividad')),
    creado_por text not null default '',
    creado_en timestamptz not null default now()
);

alter table public.eventos_calendario add column if not exists titulo text not null default '';
alter table public.eventos_calendario add column if not exists descripcion text not null default '';
alter table public.eventos_calendario add column if not exists fecha date;
alter table public.eventos_calendario add column if not exists tipo text not null default 'evento';
alter table public.eventos_calendario add column if not exists creado_por text not null default '';
alter table public.eventos_calendario add column if not exists creado_en timestamptz not null default now();

create table if not exists public.sugerencias (
    id bigint generated by default as identity primary key,
    usuario text not null default '',
    tipo text not null check (tipo in ('sugerencia', 'reporte')),
    mensaje text not null,
    fecha timestamptz not null default now(),
    estado text not null default 'pendiente'
);

alter table public.sugerencias add column if not exists estado text not null default 'pendiente';

alter table public.app_configuracion enable row level security;
alter table public.eventos_calendario enable row level security;
alter table public.sugerencias enable row level security;

revoke all on public.app_configuracion, public.eventos_calendario, public.sugerencias from public, anon;
grant select on public.app_configuracion, public.eventos_calendario to authenticated;
grant insert, update on public.app_configuracion to authenticated;
grant insert, update, delete on public.eventos_calendario to authenticated;
grant select, insert, update on public.sugerencias to authenticated;

do $$
declare
    policy_record record;
begin
    for policy_record in
        select schemaname, tablename, policyname
          from pg_policies
         where schemaname = 'public'
           and tablename = any(array['app_configuracion', 'eventos_calendario', 'sugerencias'])
    loop
        execute format(
            'drop policy if exists %I on %I.%I',
            policy_record.policyname,
            policy_record.schemaname,
            policy_record.tablename
        );
    end loop;
end;
$$;

drop policy if exists app_configuracion_read_staff on public.app_configuracion;
create policy app_configuracion_read_staff on public.app_configuracion
    for select to authenticated using (private.is_staff());
drop policy if exists app_configuracion_insert_admin on public.app_configuracion;
create policy app_configuracion_insert_admin on public.app_configuracion
    for insert to authenticated with check (private.is_admin());
drop policy if exists app_configuracion_update_admin on public.app_configuracion;
create policy app_configuracion_update_admin on public.app_configuracion
    for update to authenticated using (private.is_admin()) with check (private.is_admin());

drop policy if exists eventos_calendario_read_staff on public.eventos_calendario;
create policy eventos_calendario_read_staff on public.eventos_calendario
    for select to authenticated using (private.is_staff());
drop policy if exists eventos_calendario_insert_admin on public.eventos_calendario;
create policy eventos_calendario_insert_admin on public.eventos_calendario
    for insert to authenticated with check (private.is_admin());
drop policy if exists eventos_calendario_update_admin on public.eventos_calendario;
create policy eventos_calendario_update_admin on public.eventos_calendario
    for update to authenticated using (private.is_admin()) with check (private.is_admin());
drop policy if exists eventos_calendario_delete_admin on public.eventos_calendario;
create policy eventos_calendario_delete_admin on public.eventos_calendario
    for delete to authenticated using (private.is_admin());

drop policy if exists sugerencias_insert_staff on public.sugerencias;
create policy sugerencias_insert_staff on public.sugerencias
    for insert to authenticated with check (private.is_staff());
drop policy if exists sugerencias_read_admin on public.sugerencias;
create policy sugerencias_read_admin on public.sugerencias
    for select to authenticated using (private.is_admin());
drop policy if exists sugerencias_update_admin on public.sugerencias;
create policy sugerencias_update_admin on public.sugerencias
    for update to authenticated using (private.is_admin()) with check (private.is_admin());

commit;
